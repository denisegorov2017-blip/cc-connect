func (i *I18n) reasoningEffortLabel(effort string) string {
	if i != nil && i.CurrentLang() == LangRussian {
		switch effort {
		case "low":
			return "Низкая"
		case "medium":
			return "Средняя"
		case "high":
			return "Высокая"
		case "xhigh":
			return "Максимум"
		}
	}
	return effort
}
